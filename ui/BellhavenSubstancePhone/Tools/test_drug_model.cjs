const fs=require('fs'),assert=require('assert'),path=require('path');
const e=require('../SourceUI/drug_engine.js');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'../Config/DrugProfiles.json'),'utf8'));
let tests=0;function check(cond,message){assert(cond,message);tests++}
check(e.validateConfig(cfg).length===0,'All profiles valid');
check(cfg.drugs.length===19,'19 independently tunable profiles');
check(e.classSorted(cfg)[0].class==='Opioids','Classes ordered');
const a=cfg.drugs.find(d=>d.id==='morphine'),b=cfg.drugs.find(d=>d.id==='codeine');
check(a.tolerance.gainPerExposure!==b.tolerance.gainPerExposure,'Distinct drug tolerance values');
check(e.activeExposure(a,0)===0,'No immediate exposure at tick zero');
check(e.activeExposure(a,5,2)>e.activeExposure(a,5,1),'Fictional exposure responds to amount');
check(e.activeExposure(a,5,1)>e.activeExposure(a,5,.001),'Tiny exposure is tiny');
check(e.response(a,10,{drugTolerance:{morphine:3}},'reward','oral')<e.response(a,10,{},'reward','oral'),'Tolerance lowers subjective response');
const altered=JSON.parse(JSON.stringify(a));altered.timeCourse.residualTailFactor=.7;
check(e.activeExposure(altered,100)>e.activeExposure(a,100),'Residual tail is used by engine');
const rule=cfg.interactions[0];
check(e.interactionAmount(rule,1,0,'sedation')===0,'No second exposure => no interaction');
check(e.interactionAmount(rule,1,.001,'sedation')<.001,'Trace does not trigger full boost');
check(e.interactionAmount(rule,1,1,'sedation')>e.interactionAmount(rule,1,.001,'sedation'),'Continuously scaled interaction');
let state=e.advanceAdaptation(cfg,{}, {morphine:1,alprazolam:1},1);
check(state.drugTolerance.morphine!==state.drugTolerance.alprazolam,'Individual tolerance gains');
check(state.dependence.morphine>0&&state.dependence.alprazolam>0,'Independent multiple dependences');
check(state.familyTolerance.Opioids>0&&state.familyTolerance.Benzodiazepines>0,'Separate family tolerance');
const recovered=e.advanceAdaptation(cfg,state,{},60);
check(recovered.familyTolerance.Opioids<state.familyTolerance.Opioids,'Family tolerance recovers without exposure');
check(recovered.familyTolerance.Benzodiazepines<state.familyTolerance.Benzodiazepines,'Benzo family recovers independently');
// Editing one profile never mutates another profile or an existing character record.
const cfg2=JSON.parse(JSON.stringify(cfg));
const duplicated=e.cloneProfile(cfg2,'morphine','fictional_variant','Fictional Variant');
check(duplicated.id==='fictional_variant','Cloned independent profile');
check(e.validateConfig(cfg2).length===0,'Duplicated profile validates');
const oldExposure=e.activeExposure(duplicated,8);duplicated.timeCourse.decayHalfLifeTicks*=2;
check(e.activeExposure(duplicated,8)>oldExposure,'Clone decay affects only clone');
check(cfg2.drugs.find(d=>d.id==='morphine').timeCourse.decayHalfLifeTicks===a.timeCourse.decayHalfLifeTicks,'Source unchanged');
const cfg3=JSON.parse(JSON.stringify(cfg));cfg3.drugs.find(d=>d.id==='morphine').tolerance.gainPerExposure*=2;
const x=e.advanceAdaptation(cfg,{}, {morphine:.9,alprazolam:1},1);
const y=e.advanceAdaptation(cfg3,{}, {morphine:.9,alprazolam:1},1);
check(y.drugTolerance.morphine>x.drugTolerance.morphine,'Edited per-drug gain used');
check(y.drugTolerance.alprazolam===x.drugTolerance.alprazolam,'No cross-drug direct gain mutation');
const cfg4=JSON.parse(JSON.stringify(cfg));cfg4.drugs.find(d=>d.id==='morphine').tolerance.clearanceGainFraction=1;
const burst=e.advanceAdaptation(cfg4,{}, {morphine:1},1);
const waning=e.advanceAdaptation(cfg4,burst, {morphine:.2},1);
check(waning.drugTolerance.morphine>burst.drugTolerance.morphine,'Clearance-weighted tolerance banking works');
const high=e.advanceAdaptation(cfg,{}, {morphine:3},1);
const low=e.advanceAdaptation(cfg,{}, {morphine:1},1);
check(high.drugTolerance.morphine>low.drugTolerance.morphine*3,'High-use surge changes gain');
const cueBase={compulsiveness:{morphine:3}};
check(e.cravingPressure(cfg,cueBase,'morphine',.1)===0,'No conditioned craving during main high');
let cueState=cueBase;for(let i=0;i<20;i++)cueState=e.recordEarlyRedose(cfg,cueState,'morphine',.4);
check(cueState.conditionedCue.morphine<.6,'Repeated early redosing moves expectation earlier');
check(e.cravingPressure(cfg,cueState,'morphine',.55)>e.cravingPressure(cfg,cueBase,'morphine',.55),'Early cravings become possible with learned association');
const relaxed=e.advanceAdaptation(cfg,cueState,{},200);
check(relaxed.conditionedCue.morphine>cueState.conditionedCue.morphine,'Conditioned cue decays towards usual late-comedown baseline');
// All route definitions are abstract game coefficients, not human dose conversion.
check(cfg.drugs.every(d=>d.id&&d.reference&&d.class&&d.timeCourse.routeProfiles),'Stable IDs and profiles');
console.log(`PASS: ${tests} model assertions; ${cfg.drugs.length} live profiles, ${cfg2.drugs.length} after safe clone.`);
